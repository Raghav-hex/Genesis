const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const style = require('../pixel-style.js');
const root = path.join(__dirname, '..');
assert.equal(style.constants.SCALE, 3, 'logical pixels must be enlarged at an integer scale');
assert.equal(style.constants.WIDTH, 80);
assert.equal(style.constants.HEIGHT, 48);
assert.equal(style.constants.PALETTE.length, 16, 'the visual language uses a shared 16-colour palette');
assert.ok(style.constants.PALETTE.includes('#18211C'), 'shared outline ink');
assert.ok(style.constants.PALETTE.includes('#79974A'), 'shared moss colour');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
assert.ok(html.includes('<script src="pixel-style.js"></script>'), 'renderer loads before character modules');
assert.ok(html.includes('GenesisPixelStyle.draw(ctx,dir,pixelCtx=>'), 'all creature species use the shared pixel renderer');
assert.ok(html.includes("GenesisMossling.draw(pixelCtx"), 'Mossling is routed through the pixel renderer');
assert.ok(html.includes("GenesisVineback.draw(pixelCtx"), 'Vineback is routed through the pixel renderer');
const vineback = fs.readFileSync(path.join(root, 'vineback.js'), 'utf8');
assert.ok(vineback.includes('#60764a') || vineback.includes('#60764A'), 'Vineback uses the shared moss/stone material ramp');
assert.ok(!vineback.includes('#b96e61'), 'old independent red/purple ramp removed');
console.log('Genesis pixel-style tests passed: shared 16-colour palette, integer pixel scale, HTML integration, all creature types wired through renderer.');
